@app.get("/api/presets")
def get_presets():
    """
    Returns curated benchmark frontend error cases for instant testing.
    """
    return diff_generator.presets

@app.get("/api/knowledge")
def search_knowledge(q: Optional[str] = ""):
    """
    Queries the RAG knowledge base.
    """
    results = rag_engine.query(q, top_k=6)
    return {
        "total_results": len(results),
        "results": results
    }

@app.post("/api/telemetry")
def receive_telemetry(event: TelemetryEvent):
    """
    Ingests real-time console.error events from the Chrome Extension or Vite plugin.
    """
    # Auto-diagnose the incoming telemetry event
    sanitized_msg, _ = PrivacySanitizer.sanitize(event.error_message)
    classification = ErrorClassifier.classify(sanitized_msg)
    diff = diff_generator.generate(classification, sanitized_msg)

    return {
        "received": True,
        "event_id": f"tel-{int(time.time()*1000)}",
        "auto_diagnosis": diff
    }
