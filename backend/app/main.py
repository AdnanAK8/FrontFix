@app.post("/api/diagnose")
def diagnose(req: DiagnoseRequest):
    """
    Main diagnostic pipeline:
    1. Redacts sensitive credentials (Privacy Shield).
    2. Classifies error into domain & severity.
    3. Queries RAG documentation vectors.
    4. Generates side-by-side AST code diff & resolution card.
    """
    start_time = time.time()
    
    # 1. Privacy Sanitization
    sanitized_input = req.raw_error
    redactions_meta = {}
    if req.enable_privacy_shield:
        sanitized_input, redactions_meta = PrivacySanitizer.sanitize(req.raw_error)

    # 2. Classification & Routing
    classification = ErrorClassifier.classify(sanitized_input)

    # 3. RAG Context Retrieval
    rag_chunks = rag_engine.query(sanitized_input, top_k=2)

    # 4. Code Diff & Solution Synthesis
    diagnostic_card = diff_generator.generate(classification, sanitized_input)
    
    elapsed = round(time.time() - start_time, 3)

    return {
        "success": True,
        "latency_seconds": elapsed,
        "privacy_shield_applied": req.enable_privacy_shield,
        "redactions": redactions_meta,
        "classification": classification,
        "diagnostic_card": diagnostic_card,
        "rag_sources": rag_chunks
    }

