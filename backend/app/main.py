import time
from typing import Dict, Any, Optional, List
from fastapi import FastAPI, HTTPException, Body
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

from .services.sanitizer import PrivacySanitizer
from .services.classifier import ErrorClassifier
from .services.rag_engine import RAGEngine
from .services.diff_generator import DiffGenerator

app = FastAPI(
    title="FrontFix AI API",
    description="Team B: Autonomous AI-Powered Frontend Support Chatbot & Diagnostics Backend",
    version="1.0.0"
)

# Enable CORS for local web development and browser extensions
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Initialize Core Services
rag_engine = RAGEngine()
diff_generator = DiffGenerator()

